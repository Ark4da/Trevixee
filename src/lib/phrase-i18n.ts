let windows1251Reverse: Map<string, number> | null = null;

function getWindows1251Reverse() {
  if (windows1251Reverse) return windows1251Reverse;

  const decoder = new TextDecoder("windows-1251");
  windows1251Reverse = new Map<string, number>();
  for (let byte = 0; byte <= 255; byte += 1) {
    windows1251Reverse.set(decoder.decode(Uint8Array.of(byte)), byte);
  }
  return windows1251Reverse;
}

function repairMojibake(value: string) {
  if (!/[РСВвЂ]/.test(value)) return value;

  const reverse = getWindows1251Reverse();
  const bytes: number[] = [];
  for (const char of value) {
    const byte = reverse.get(char);
    if (byte === undefined) return value;
    bytes.push(byte);
  }

  try {
    const decoded = new TextDecoder("utf-8", { fatal: true }).decode(Uint8Array.from(bytes));
    return /[А-Яа-яЁё]/.test(decoded) ? decoded : value;
  } catch {
    return value;
  }
}

function addPair(en: string | undefined, ru: string | undefined) {
  if (!en || !ru) return;
  const cleanEn = repairMojibake(en.trim());
  const cleanRu = repairMojibake(ru.trim());
  if (!cleanEn || !cleanRu || cleanEn.includes("{") || cleanRu.includes("{")) return;
  toRu.set(cleanEn, cleanRu);
  toEn.set(cleanRu, cleanEn);
}

