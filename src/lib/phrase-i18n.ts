export function translatePhrase(value: string, lang: Lang): string {
  const match = value.match(whitespace);
  if (!match) return value;

  const [, before, core, after] = match;
  const normalized = repairMojibake(core.replace(/\s+/g, " ").trim());
  if (!normalized) return value;

  const translated = lang === "ru" ? toRu.get(normalized) : toEn.get(normalized);
  const patternTranslated = translated ?? translatePattern(normalized, lang);
  return patternTranslated ? `${before}${patternTranslated}${after}` : value;
}

export function hasPhraseTranslation(value: string, lang: Lang): boolean {
  const normalized = repairMojibake(value.replace(/\s+/g, " ").trim());
  return lang === "ru"
    ? toRu.has(normalized) || Boolean(translatePattern(normalized, lang))
    : toEn.has(normalized) || Boolean(translatePattern(normalized, lang));
}
